class DuoQuizAnswers {
    static getHighlightedAnswer(tid, localizedString) {
        if (!Config.Config.config.HighlightDuoQuizAnswers || !tid || !this.correctAnswerTids.has(tid)) {
            return null;
        }
        if (localizedString.isNull()) {
            return null;
        }
        var text = StringObject.StringObject.read(localizedString);
        if (!text || text === tid) {
            return null;
        }
        var highlightedText = "<c00FF00>".concat(text.replace(new RegExp("<c[0-9a-f]+>|<\\/c>", "g"), ""), "</c>");
        var highlightedString = this.highlightedStrings.get(highlightedText);
        if (!highlightedString) {
            highlightedString = StringObject.StringObject.create(highlightedText);
        }
        return highlightedString;
    }
}

